class Processor:
    def __init__(self, stringsloader):
        self.db = Database()
        self.stringsloader = stringsloader
        self.log = logging.getLogger('main')
        self.idgen = itertools.count()
        self.forms = {}


    def loadForms(self, path):
        if path is None:
            return
        for fname in sorted(os.listdir(path)):
            if fname.endswith('.frm'):
                # load
                f = Form()
                f.load(path+'/'+fname)
                doctype = f.name.lower()
                self.forms[doctype] = f
                # add db func
                if f.query:
                    self.db.registerQueryFunc(doctype, f.query)
                # add report generator
                report_generators[doctype] = TemplateFiller(f)


    def newRequest(self):
        req = Request()
        req.documenttype_enum += self.forms.keys()
        return req


